# -*- coding: utf-8 -*-
"""Обновление паспорта «Мир по кусочкам»: v1.1 -> v1.2 (хостинг и свободный доступ)."""
import io, os

SRC = '/home/z/my-project/download/game-passport-v1.9.dsl'
DST = '/home/z/my-project/download/game-passport-mir-po-kusochkam-v1.2.dsl'

with io.open(SRC, 'r', encoding='utf-8') as f:
    t = f.read()

orig = t

# 1. Шапка: версия паспорта и дата
t = t.replace(
    '#  Версия игры: 1.9  ·  Версия паспорта: 1.1  ·  Дата: 12.11.2026',
    '#  Версия игры: 1.9  ·  Версия паспорта: 1.2  ·  Дата: 13.11.2026\n'
    '#  v1.2: добавлен раздел 12 «ХОСТИНГ И СВОБОДНЫЙ ДОСТУП» — правило\n'
    '#  проекта: у каждой игры семьи постоянный бесплатный адрес (GitHub Pages).'
)

# 2. метод_работы: строка «обновление» устарела (ссылка чата умирает с сессией)
t = t.replace(
    'метод_работы {\n  обновление: "правки делаются на моей ссылке — у всех игроков обновляется автоматически"',
    'метод_работы {\n  обновление: "правки делаются в рабочем проекте; постоянный адрес появится после переноса игры на GitHub Pages (раздел 12)"'
)

# 3. План: добавить правку 1.10 (перенос на GitHub Pages) перед строкой «отменено»
t = t.replace(
    '  отменено: "подсказка «Покажи мне» — решением заказчика НЕ делаем (12.11.2026)"',
    '  правка "1.10" { статус: В ПЛАНЕ, состав: "перенос игры на GitHub Pages: статический экспорт Next.js, постоянный бесплатный адрес, офлайн через service worker" }\n'
    '  отменено: "подсказка «Покажи мне» — решением заказчика НЕ делаем (12.11.2026)"'
)

# 4. Идеи → группа «Техника»: добавить идею про GitHub Pages
t = t.replace(
    '    идея { статус: НОВАЯ,    суть: "страничка «что нового» в игре: описание версии простыми словами" }\n  }\n}',
    '    идея { статус: НОВАЯ,    суть: "страничка «что нового» в игре: описание версии простыми словами" }\n'
    '    идея { статус: В ПЛАНЕ,  суть: "перенос игры на GitHub Pages — вечный бесплатный адрес, свободный доступ всегда (раздел 12 паспорта, правка v1.10)" }\n  }\n}'
)

# 5. Новый раздел 12 перед финальной чертой
section12 = '''

# ------------------------------ 12. ХОСТИНГ И СВОБОДНЫЙ ДОСТУП ------------------------------

# Правило проекта (13.11.2026): игры семьи живут на постоянном бесплатном адресе
# и НЕ зависят от рабочих сессий нейросети — сессия кончилась, игра осталась.

хостинг_и_доступ {
  правило   : "каждая игра получает постоянный адрес на GitHub Pages (бесплатно, навсегда); ссылки из чата — только временное решение"
  морской_бой { адрес: "https://gohsa04071988-glitch.github.io/captains-game/", статус: ГОТОВО, примечание: "заливает заказчик сам: скачать captains.html → переименовать в index.html → залить в репозиторий" }
  мир_по_кусочкам {
    сейчас  : "постоянного адреса пока нет — игра открывается по ссылке из рабочего чата, и когда сессия заканчивается, ссылка умирает"
    запас   : "полные копии v1.9 хранятся всегда: download/mir-po-kusochkam-v1.9.zip и download/game-archive/v1.9-polnyi-oflain/"
    как_перенести: "статический экспорт Next.js (output: 'export') → папка out/ → в репозиторий GitHub Pages; правка-кандидат v1.10. Проверку /api/version при этом отключить — плашку «Обновить» подхватит service worker"
    статус  : В ПЛАНЕ
  }
  паспорта {
    пазл    : "download/game-passport-mir-po-kusochkam-v1.2.dsl (этот файл)"
    бой     : "download/game-passport-captains-v1.0.dsl"
    суть    : "по паспорту любая новая сессия нейросети восстанавливает контекст игры с нуля — «умершая сессия» больше не теряет игру"
  }
}
'''

marker = '''
# ==================================================================
#  КОНЕЦ ПАСПОРТА · «Мир по кусочкам» v1.9 · 12.11.2026
# =================================================================='''
footer_new = '''
# ==================================================================
#  КОНЕЦ ПАСПОРТА · «Мир по кусочкам» v1.9 · паспорт v1.2 · 13.11.2026
# =================================================================='''

if marker not in t:
    raise SystemExit('ОШИБКА: не найден футер паспорта')
t = t.replace(marker, section12 + footer_new)

if t == orig:
    raise SystemExit('ОШИБКА: ни одна замена не применилась')

with io.open(DST, 'w', encoding='utf-8') as f:
    f.write(t)

# Проверки: баланс скобок и ключевые строки
opens = t.count('{'); closes = t.count('}')
print('Записан:', DST)
print('Строк:', t.count(chr(10)) + 1, '· Скобки { = %d, } = %d' % (opens, closes))
for probe in ['Версия паспорта: 1.2', 'хостинг_и_доступ', 'правка "1.10"',
              'перенос игры на GitHub Pages — вечный бесплатный адрес',
              'паспорт v1.2 · 13.11.2026']:
    print(('OK  ' if probe in t else 'НЕТ ') + probe)
